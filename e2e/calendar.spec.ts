import { test, expect } from "@playwright/test"
import { capabilityContent, seedCapabilityNote } from "./editor-capability-seed"

test("日历复用组件并保存 Markdown，刷新保留日程", async ({ page }, info) => {
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  const now = new Date(); now.setHours(10, 0, 17, 123)
  const end = new Date(now.getTime() + 3600000)
  const body = `---\nswell_event: 1\nevent_title: '设计讨论'\nevent_start: ${now.toISOString()}\nevent_end: ${end.toISOString()}\nevent_category: work\ntags: [design]\n---\n# 会议记录\n\n必须保留的正文\n`
  await seedCapabilityNote(page, body)
  await page.evaluate(() => localStorage.setItem("swell-note:webdav-config:v1", JSON.stringify({ provider: "jianguoyun", remotePath: "/Swell/", serverUrl: "https://dav.jianguoyun.com/dav/", username: "calendar@example.com" })))
  await page.goto("/#/calendar")
  await expect(page.locator(".note-calendar-engine")).toBeVisible()
  const mobile = info.project.name.includes("mobile")
  await expect(page.locator(mobile ? ".swell-calendar-agenda-event" : ".swell-calendar-month-event").filter({ hasText: "设计讨论" }).first()).toBeVisible()
  await page.locator(mobile ? ".swell-calendar-agenda-event" : ".note-calendar-item").filter({ hasText: "设计讨论" }).first().click()
  await page.getByRole("button", { name: "编辑日程", exact: true }).click()
  await page.getByLabel("日程名称", { exact: true }).fill("调整后的讨论")
  await page.getByRole("button", { name: "保存日程", exact: true }).click()
  await expect.poll(() => capabilityContent(page)).toContain("调整后的讨论")
  expect(await capabilityContent(page)).toContain("必须保留的正文")
  expect(await capabilityContent(page)).toContain("tags: [design]")
  expect(await capabilityContent(page)).toContain(now.toISOString())
  expect(await capabilityContent(page)).toContain(end.toISOString())
  await page.reload()
  await expect(page.locator(mobile ? ".swell-calendar-agenda-event" : ".note-calendar-item").filter({ hasText: "调整后的讨论" }).first()).toBeVisible()
  await page.getByRole("button", { name: "新建日程", exact: true }).click()
  await page.getByLabel("日程名称", { exact: true }).fill("第二条安排")
  await page.getByRole("button", { name: "保存日程", exact: true }).click()
  await expect(page.locator(mobile ? ".swell-calendar-agenda-event" : ".note-calendar-item").filter({ hasText: "第二条安排" }).first()).toBeVisible()
  await expect.poll(() => page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>(resolve => { const request = indexedDB.open("swell-note-vault-cache", 3); request.onsuccess = () => resolve(request.result) })
    const documents = await new Promise<{ content: string }[]>(resolve => { const request = db.transaction("documents").objectStore("documents").getAll(); request.onsuccess = () => resolve(request.result) })
    db.close()
    return documents.some(document => document.content.includes("第二条安排"))
  })).toBe(true)
  await page.reload()
  await expect(page.locator(mobile ? ".swell-calendar-agenda-event" : ".note-calendar-item").filter({ hasText: "第二条安排" }).first()).toBeVisible()
  if (mobile) await page.getByRole("button", { name: "月历", exact: true }).click()
  await expect(page.locator(".swell-calendar-month-view")).toBeVisible()
  const key = `${now.getFullYear()}-${String(now.getMonth()+1).padStart(2,"0")}-${String(now.getDate()).padStart(2,"0")}`
  await page.getByRole("button", { name: key, exact: true }).click()
  if (mobile) await expect(page.locator(".swell-calendar-agenda-view")).toBeVisible()
  else {
    await expect(page.getByRole("dialog")).toBeVisible()
    await page.keyboard.press("Escape")
  }
  await page.screenshot({ path: `docs/calendar/${mobile ? "mobile" : "desktop"}.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  await page.screenshot({ path: `docs/calendar/${mobile ? "mobile" : "desktop"}-dark.png`, fullPage: true })
  if (!mobile) {
    await page.getByRole("button", { name: "周", exact: true }).click()
    await expect(page.getByRole("rowgroup")).toBeVisible()
    await expect(page.locator(".note-calendar-engine").getByRole("button", { name: "第二条安排 10:00", exact: true })).toBeVisible()
  } else {
    await page.setViewportSize({ width: 320, height: 740 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.getByRole("button", { name: "日", exact: true }).click()
  await expect(page.locator(".swell-calendar-day-view")).toBeVisible()
  const dayEvent = page.locator(".note-calendar-engine").getByRole("button", { name: "第二条安排 10:00", exact: true })
  await dayEvent.scrollIntoViewIfNeeded()
  await expect(dayEvent).toBeVisible()
  await page.getByRole("button", { name: "下一页", exact: true }).click()
  const tomorrow = new Date(now); tomorrow.setDate(tomorrow.getDate() + 1)
  await expect(page.locator(".note-calendar-date-nav strong")).toHaveText(`${tomorrow.getFullYear()} 年 ${tomorrow.getMonth() + 1} 月 ${tomorrow.getDate()} 日`)
  await expect(dayEvent).toHaveCount(0)
  await page.getByRole("button", { name: "新建日程", exact: true }).click()
  await expect(page.getByLabel("开始时间", { exact: true })).toHaveValue(`${tomorrow.getFullYear()}-${String(tomorrow.getMonth()+1).padStart(2,"0")}-${String(tomorrow.getDate()).padStart(2,"0")}T10:00`)
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "上一页", exact: true }).click()
  await dayEvent.scrollIntoViewIfNeeded()
  await expect(dayEvent).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `docs/calendar/${mobile ? "mobile" : "desktop"}-day.png`, fullPage: true })
  expect(errors).toEqual([])
})


test("桌面空白格点击、跨日拖选和周时间选择进入新建表单", async ({ page }, info) => {
  test.skip(info.project.name.includes("mobile"), "桌面鼠标选择入口")
  await seedCapabilityNote(page, "# 独立测试笔记")
  await page.evaluate(() => localStorage.setItem("swell-note:webdav-config:v1", JSON.stringify({ provider: "jianguoyun", remotePath: "/Swell/", serverUrl: "https://dav.jianguoyun.com/dav/", username: "calendar@example.com" })))
  await page.goto("/#/calendar")
  await page.reload()
  await expect(page.getByRole("button", { name: "新建日程", exact: true })).toBeEnabled()
  const cells = page.locator(".swell-calendar-month-cell")
  const first = cells.nth(10)
  const last = cells.nth(12)
  const firstKey = await first.getByRole("button").getAttribute("aria-label")
  const lastKey = await last.getByRole("button").getAttribute("aria-label")
  await first.click({ position: { x: 40, y: 60 } })
  await expect(page.getByLabel("开始时间", { exact: true })).toHaveValue(`${firstKey}T10:00`)
  await page.keyboard.press("Escape")
  // 取消不应产生事件；跨格拖选只打开预填表单。
  await expect(page.locator(".swell-calendar-month-event")).toHaveCount(0)
  const a = await first.boundingBox(); const b = await last.boundingBox()
  if (!a || !b) throw new Error("月格不可见")
  await page.mouse.move(a.x + 40, a.y + 60)
  await page.mouse.down()
  await page.mouse.move(b.x + 40, b.y + 60, { steps: 12 })
  await page.mouse.up()
  await expect(page.getByLabel("开始时间", { exact: true })).toHaveValue(`${firstKey}T10:00`)
  await expect(page.getByLabel("结束时间", { exact: true })).toHaveValue(`${lastKey}T11:00`)
  await page.getByLabel("日程名称", { exact: true }).fill("拖选创建的安排")
  await page.getByRole("button", { name: "保存日程", exact: true }).click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(page.locator(".swell-calendar-month-event").filter({ hasText: "拖选创建的安排" }).first()).toBeVisible()
  await expect.poll(() => page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>(resolve => { const req = indexedDB.open("swell-note-vault-cache", 3); req.onsuccess = () => resolve(req.result) })
    const docs = await new Promise<{content: string}[]>(resolve => { const req = db.transaction("documents").objectStore("documents").getAll(); req.onsuccess = () => resolve(req.result) })
    db.close()
    return docs.some(doc => doc.content.includes("拖选创建的安排"))
  })).toBe(true)
  await page.reload()
  await expect(page.locator(".swell-calendar-month-event").filter({ hasText: "拖选创建的安排" }).first()).toBeVisible()
  for (const view of ["周", "日"]) {
  await page.getByRole("button", { name: view, exact: true }).click()
  const grid = page.locator(".swell-calendar-time-columns")
  await expect(grid).toBeVisible()
  const box = await grid.boundingBox()
  if (!box) throw new Error("周网格不可见")
  await page.mouse.click(box.x + box.width * 0.5, box.y + 140)
  await expect(page.getByRole("dialog")).toBeVisible()
  const clickStart = await page.getByLabel("开始时间", { exact: true }).inputValue()
  expect(clickStart).toBeTruthy()
  await page.keyboard.press("Escape")
  await page.mouse.move(box.x + box.width * 0.5, box.y + 140)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.5, box.y + 230, { steps: 10 })
  await page.mouse.up()
  await expect(page.getByRole("dialog")).toBeVisible()
  expect(new Date(await page.getByLabel("结束时间", { exact: true }).inputValue()).getTime()).toBeGreaterThan(new Date(await page.getByLabel("开始时间", { exact: true }).inputValue()).getTime())
  await page.keyboard.press("Escape")
  }
})

for (const view of ["日", "周"]) {
  test(`${view}视图拖动和调整时长写回原笔记`, async ({ page }, info) => {
    const mobile = info.project.name.includes("mobile")
    test.skip(mobile && view === "周", "手机入口只展示日视图")
    const touch = mobile ? await page.context().newCDPSession(page) : null
    async function drag(x: number, y: number, toX: number, toY: number) {
      if (touch) {
        await touch.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y }] })
        for (let i = 1; i <= 15; i++) await touch.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: x + (toX - x) * i / 15, y: y + (toY - y) * i / 15 }] })
        await touch.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] })
      } else {
        await page.mouse.move(x, y); await page.mouse.down()
        await page.mouse.move(toX, toY, { steps: 15 }); await page.mouse.up()
      }
    }
    const start = new Date(); start.setHours(10, 0, 0, 0)
    const end = new Date(start.getTime() + 3600000)
    await seedCapabilityNote(page, `---\nswell_event: 1\nevent_title: "拖动讨论"\nevent_start: ${start.toISOString()}\nevent_end: ${end.toISOString()}\nevent_category: personal\ntags: [keep]\n---\n必须保留的原笔记正文\n`)
    await page.evaluate(() => localStorage.setItem("swell-note:webdav-config:v1", JSON.stringify({ provider: "jianguoyun", remotePath: "/Swell/", serverUrl: "https://dav.jianguoyun.com/dav/", username: "calendar@example.com" })))
    await page.goto("/#/calendar")
    await page.reload()
    await page.getByRole("button", { name: view, exact: true }).click()
    const id = "webdav:/Swell/测试/第一篇.md"
    const card = page.getByTestId(`event-card-${id}`)
    await card.scrollIntoViewIfNeeded()
    const box = await card.boundingBox()
    if (!box) throw new Error("日程不可见")
    // 周视图同时跨列与改时间，日视图在同一天改时间。
    const grid = await page.locator(".swell-calendar-time-columns").boundingBox()
    const dayDelta = (start.getDay() + 6) % 7 === 6 ? -1 : 1
    const dx = view === "周" && grid ? grid.width / 7 * dayDelta : 0
    await drag(box.x + box.width / 2, box.y + box.height / 2, box.x + box.width / 2 + dx, box.y + box.height * 1.5)
    await expect.poll(() => capabilityContent(page)).not.toContain(`event_start: ${start.toISOString()}`)
    const moved = await capabilityContent(page)
    const readTime = (body: string, field: string) => Date.parse(body.match(new RegExp(`${field}: ([^\\n]+)`))![1])
    expect(readTime(moved, "event_end") - readTime(moved, "event_start")).toBe(3600000)
    const movedDate = new Date(readTime(moved, "event_start"))
    const expectedDate = new Date(start); if (view === "周") expectedDate.setDate(expectedDate.getDate() + dayDelta)
    expect(movedDate.toDateString()).toBe(expectedDate.toDateString())
    await card.scrollIntoViewIfNeeded()
    const handle = page.getByTestId(`resize-handle-bottom-${id}`)
    const handleBox = await handle.boundingBox()
    const movedBox = await card.boundingBox()
    if (!handleBox || !movedBox) throw new Error("时长调整手柄不可见")
    await drag(handleBox.x + handleBox.width / 2, handleBox.y + handleBox.height / 2, handleBox.x + handleBox.width / 2, handleBox.y + movedBox.height)
    await expect.poll(async () => readTime(await capabilityContent(page), "event_end")).toBeGreaterThan(readTime(moved, "event_end"))
    const resized = await capabilityContent(page)
    expect(readTime(resized, "event_start")).toBe(readTime(moved, "event_start"))
    expect(resized).toContain('event_title: "拖动讨论"')
    expect(resized).toContain("event_category: personal")
    expect(resized).toContain("tags: [keep]")
    expect(resized).toContain("必须保留的原笔记正文")
    await page.reload()
    expect(await capabilityContent(page)).toBe(resized)
    // 刷新现在恢复原视图；直接验收恢复结果，避免切视图时抓取即将卸载的旧卡片。
    await expect(page.getByRole("button", { name: view, exact: true })).toHaveAttribute("aria-pressed", "true")
    await card.scrollIntoViewIfNeeded()
    await expect(card).toBeVisible()
    await expect(page.getByRole("alert")).toHaveCount(0)
  })
}

test("日程改期保存被拒时恢复卡片位置和原笔记", async ({ page }, info) => {
  test.skip(info.project.name.includes("mobile"), "保存拒绝回滚验证")
  const start = new Date(); start.setHours(10, 0, 0, 0)
  const body = `---\nswell_event: 1\nevent_title: >\n  手写多行标题\nevent_start: ${start.toISOString()}\nevent_end: ${new Date(start.getTime() + 3600000).toISOString()}\nevent_category: work\n---\n原始正文\n`
  await seedCapabilityNote(page, body)
  await page.goto("/#/calendar")
  await page.getByRole("button", { name: "日", exact: true }).click()
  const card = page.getByTestId("event-card-webdav:/Swell/测试/第一篇.md")
  await card.scrollIntoViewIfNeeded()
  const beforeTop = await card.evaluate(el => (el as HTMLElement).style.top)
  const before = await card.boundingBox()
  if (!before) throw new Error("日程不可见")
  await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2)
  await page.mouse.down()
  await page.mouse.move(before.x + before.width / 2, before.y + before.height * 1.5, { steps: 15 })
  await page.mouse.up()
  await expect(page.getByRole("alert")).toContainText("多行内容")
  expect(await capabilityContent(page)).toBe(body)
  // 错误提示会让整个网格下移，比较卡片相对时间网格的位置。
  await expect.poll(() => card.evaluate(el => (el as HTMLElement).style.top)).toBe(beforeTop)
  await expect(card).toContainText("10:00")
})
